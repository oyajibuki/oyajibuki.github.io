#!/usr/bin/env node
/**
 * 紹介ページが無いアプリ用に、App Store の公式説明文（iTunes Lookup API）から
 * <dir>/about.html を生成する。機能・料金の文章は作文せず、ストアの記載をそのまま整形する。
 *
 *   node tools/intro-build.mjs            # ドライラン（取得して内容を表示するだけ）
 *   node tools/intro-build.mjs --write    # about.html を書く
 *
 * - 既存の <dir>/index.html（サポートページ。App Store のサポートURLに登録済み）は触らない。
 * - 既に手書きの about.html がある場合（このスクリプトの印が無い）は上書きしない。
 * - 書いたあとは  node tools/seo-build.mjs --write  で canonical / OGP / JSON-LD / sitemap に反映。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WRITE = process.argv.includes('--write');
const MARK = '<!-- generated by tools/intro-build.mjs -->';

// dir は index.html の既存サポートページ側のフォルダ名。id は App Store の ID。
const TARGETS = [
  { dir: 'danshuquest', id: '6764613044', h1: '断酒クエスト', tag: '禁酒・断酒の習慣化RPG' },
  { dir: 'undoquest', id: '6765534901', h1: '運動クエスト', tag: '運動の習慣化RPG' },
  { dir: 'benkyoquest', id: '6765785966', h1: '勉強クエスト', tag: '勉強の習慣化RPG' },
  { dir: 'hold', id: '6769427890', h1: 'HOLD', full: 'HOLD — PlunkTimer', tag: 'プランク専用のシンプルなタイマー' },
  { dir: 'devkeep', id: '6777493725', h1: 'DevKeep', tag: '個人開発者のためのアプリ管理ツール' },
  { dir: 'appguard', id: '6785254908', h1: 'AppGuard', tag: 'スマホの使いすぎを止めるアプリ制限ロック' },
  { dir: 'trustgps', id: '6790150188', h1: 'TrustGPS', tag: '必要な期間だけ共有できる位置情報アプリ' },
  { dir: 'Subsc', id: '6789902889', h1: 'シンプルサブスク管理', tag: 'サブスクを日額換算して見える化' },
  { dir: 'simpleunzip', id: '6788384543', h1: 'シンプル解凍', tag: 'zip・7zをタップだけで解凍' },
  { dir: 'nekobase', id: '6812993291', h1: 'ネコベース', tag: '多頭飼いの猫のお世話を家族や親戚と分け合う' },
];

const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const BULLET = /^[・●◎◆▶︎▶\-－]\s*/;
const HEAD = /^(■|【[^】]*】\s*$|＜|▼)/;

/** ストア説明文 → HTML。見出し(■/【】)・箇条書き(・●◎)・段落に整える */
function render(desc) {
  const lines = desc.replace(/\r/g, '').split('\n').map(l => l.replace(/\s+$/, ''));
  const out = [];
  let ul = null, para = [];
  const flushPara = () => { if (para.length) { out.push(`<p>${para.map(esc).join('<br>')}</p>`); para = []; } };
  const flushUl = () => { if (ul) { out.push(`<ul class="feature-list">${ul.join('')}</ul>`); ul = null; } };
  let afterBullet = false;
  for (const raw of lines) {
    const t = raw.trim();
    if (!t) { flushPara(); afterBullet = false; continue; }
    if (/^利用規約（EULA）|^【利用規約（EULA）】|^https?:\/\/www\.apple\.com\/legal/.test(t)) { flushPara(); afterBullet = false; continue; }
    if (HEAD.test(t)) {
      flushPara(); flushUl(); afterBullet = false;
      out.push(`<h2>${esc(t.replace(/^■\s*/, '').replace(/^【(.*)】$/, '$1'))}</h2>`);
      continue;
    }
    if (BULLET.test(t)) {
      flushPara();
      if (!ul) ul = [];
      ul.push(`<li><div><b>${esc(t.replace(BULLET, ''))}</b></div></li>`);
      afterBullet = true;
      continue;
    }
    // 箇条書きの直下の説明行は、その項目の補足にする
    if (afterBullet && ul && ul.length) {
      const last = ul.pop();
      ul.push(last.replace('</div></li>', `<span>${esc(t)}</span></div></li>`));
      continue;
    }
    flushUl();
    para.push(t);
  }
  flushPara(); flushUl();
  return out.join('\n  ');
}

const res = [];
for (const T of TARGETS) {
  const r = await fetch(`https://itunes.apple.com/lookup?id=${T.id}&country=jp`).then(x => x.json());
  const a = r.results?.[0];
  if (!a) { res.push([T.dir, '【失敗】App Store に見つからない']); continue; }

  const file = path.join(ROOT, T.dir, 'about.html');
  if (fs.existsSync(file) && !fs.readFileSync(file, 'utf8').includes(MARK)) {
    res.push([T.dir, '【スキップ】手書きの about.html があるため']); continue;
  }
  const shortName = T.h1;
  const name = T.full || T.h1;
  const icon512 = (a.artworkUrl512 || a.artworkUrl100 || '').replace(/\/512x512bb\.jpg$/, '/512x512bb.jpg');
  const first = (a.description.split('\n').find(l => l.trim() && !HEAD.test(l.trim())) || '').trim();
  const meta = first.length > 110 ? first.slice(0, 108) + '…' : first;

  const subs = ['support.html', 'privacy.html', 'terms.html']
    .filter(f => fs.existsSync(path.join(ROOT, T.dir, f)))
    .map(f => `<a href="/${T.dir}/${f}">${{ 'support.html': 'サポート / FAQ', 'privacy.html': 'プライバシーポリシー', 'terms.html': '利用規約' }[f]}</a>`);
  if (fs.existsSync(path.join(ROOT, T.dir, 'index.html'))) subs.unshift(`<a href="/${T.dir}/">サポート</a>`);
  if (T.dir === 'nekobase') subs.push('<a href="/NekoBase/support.html">サポート / FAQ</a>');

  const html = `<!DOCTYPE html>
${MARK}
<html lang="ja">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(name)}｜${esc(T.tag)}</title>
  <meta name="description" content="${esc(meta)}">
  <link rel="stylesheet" href="/common.css">
  <style>
    .feature-list { list-style:none; padding:0; margin:8px 0 0; }
    .feature-list li { padding:12px 0; border-bottom:1px solid #eee; }
    .feature-list li:last-child { border-bottom:none; }
    .feature-list b { display:block; font-size:0.96rem; }
    .feature-list span { display:block; font-size:0.85rem; color:#666; margin-top:2px; }
    .sub-links { display:flex; gap:10px; flex-wrap:wrap; margin-top:16px; }
    .sub-links a { background:#f0f0f0; color:#333 !important; padding:9px 18px; border-radius:10px; font-size:0.85rem; font-weight:600; text-decoration:none; }
    .store-note { font-size:0.8rem; color:#888; margin-top:28px; }
  </style>
</head>
<body>
  <div class="back">← <a href="/">アプリ一覧に戻る</a></div>

  <div class="app-header">
    <div class="app-icon"><img src="${esc(icon512)}" alt="${esc(shortName)}のアイコン"></div>
    <div>
      <h1>${esc(shortName)}</h1>
      <p class="app-tagline">${esc(T.tag)}</p>
    </div>
  </div>

  <p style="margin:16px 0 0;">
    <a class="btn-appstore" href="${esc(a.trackViewUrl.replace(/\?uo=\d+$/, ''))}" target="_blank" rel="noopener">App Store で開く</a>
  </p>

  <div class="sub-links">
    ${subs.join('\n    ')}
  </div>

  <hr>

  ${render(a.description)}

  <p class="store-note">この紹介文は App Store の掲載内容にもとづきます。最新の価格・機能は App Store の掲載ページをご確認ください。利用規約: <a href="https://www.apple.com/legal/internet-services/itunes/dev/stdeula/" target="_blank" rel="noopener">Apple 標準EULA</a></p>

  <footer><p>${esc(shortName)} &nbsp;·&nbsp; <a href="/">アプリ一覧</a> &nbsp;·&nbsp; <a href="/form/">お問い合わせ</a></p></footer>
</body>
</html>
`;
  if (WRITE) fs.writeFileSync(file, html);
  res.push([T.dir, `${WRITE ? '作成' : '作成予定'} about.html（${html.length}字 / 見出し${(html.match(/<h2>/g) || []).length} / 項目${(html.match(/<li>/g) || []).length}）`]);
}
console.log(WRITE ? '【書き込みモード】' : '【ドライラン】（--write で反映）');
for (const [d, s] of res) console.log(d.padEnd(12), s);
